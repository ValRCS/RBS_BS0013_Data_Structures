import {editor} from "./editor.mjs";
import {workspace} from "../../assets/js/core/algorithm-workspace.mjs";
import {presets} from "./graph-presets.mjs";
import {debugging,density,workload,quiz} from "./experiments.mjs";
import {weightedLab,structureLab,repairLab,operationLab,engineeringLab} from "./labs-v2.mjs";
import {on} from "./ui.mjs";
const graphUI=editor(g=>workload(g));
const getEditor=()=>graphUI.get();
const choose=keys=>Object.fromEntries(keys.map(k=>[k,presets[k]]));
workspace(document.getElementById("bfs-workspace"),{type:"bfs",presets:choose(["lecture","tree","cycle","disconnected","dag","star"]),initial:"lecture",getEditor});
workspace(document.getElementById("dfs-workspace"),{type:"dfs",presets:choose(["disconnected","lecture","tree","cycle","dag","loops"]),initial:"disconnected",getEditor});
workspace(document.getElementById("dijkstra-workspace"),{type:"dijkstra",presets:choose(["stale","routes","lecture"]),initial:"stale",getEditor});
weightedLab(document.getElementById("weighted-workspace"));
structureLab(document.getElementById("structure-workspace"),presets,getEditor);
repairLab(document.getElementById("repair-workspace"));
operationLab(document.getElementById("operation-workspace"),getEditor);
engineeringLab(document.getElementById("engineering-workspace"));
debugging();density();quiz();
on("density-run","click",density);
on("workload-run","click",()=>workload(getEditor()));
