import {editor} from "./editor.mjs";
import {workspace} from "../../assets/js/core/algorithm-workspace.mjs";
import {presets,fillPresets} from "./graph-presets.mjs";
import {debugging,density,workload,quiz} from "./experiments.mjs";
import {weightedLab,structureLab,engineeringLab} from "./labs-v2.mjs";
import {operationMicroscope} from "./operation-microscope.mjs";
import {invariantDebugger} from "./invariant-debugger.mjs";
import {on} from "./ui.mjs";
const workspaces={};
const graphUI=editor(g=>{workload(g);Object.values(workspaces).forEach(w=>w.refreshSource?.())});
const getEditor=()=>graphUI.get(),getSnapshot=()=>graphUI.snapshot();
const choose=keys=>Object.fromEntries(keys.map(k=>[k,presets[k]]));
function jumpToEditor(id){const a=document.getElementById("return-to-tool");a.href="#"+id;a.textContent="Return to "+(id.replace("-workspace","").replaceAll("-"," "));a.hidden=false}
const common={getEditor,getSnapshot,fillPresets,jumpToEditor};
workspaces.bfs=workspace(document.getElementById("bfs-workspace"),{type:"bfs",presets:choose(["lecture","tree","cycle","disconnected","dag","star","path","grid","diamond","k33","wheel","bridge","complete","chain","singleton"]),initial:"lecture",...common});
workspaces.dfs=workspace(document.getElementById("dfs-workspace"),{type:"dfs",presets:choose(["disconnected","lecture","tree","cycle","dag","loops","path","unbalanced","diamondDag","grid","bridge","chain"]),initial:"disconnected",...common});
workspaces.dijkstra=workspace(document.getElementById("dijkstra-workspace"),{type:"dijkstra",presets:choose(["stale","routes","equal","zero","weightedGrid","weightedDisconnected","negative","lecture"]),initial:"stale",...common});
weightedLab(document.getElementById("weighted-workspace"));
workspaces.structure=structureLab(document.getElementById("structure-workspace"),presets,getEditor,getSnapshot,jumpToEditor);
invariantDebugger(document.getElementById("repair-workspace"));
workspaces.operations=operationMicroscope(document.getElementById("operation-workspace"),getSnapshot,jumpToEditor);
engineeringLab(document.getElementById("engineering-workspace"));
debugging();density();quiz();
on("density-run","click",density);
on("workload-run","click",()=>workload(getEditor()));
for(const b of document.querySelectorAll("[data-import-tool]"))b.addEventListener("click",()=>{const key=b.dataset.importTool;workspaces[key].importGraph();location.hash=key==="operations"?"operation-workspace":key==="structure"?"structure-workspace":key+"-workspace"});
